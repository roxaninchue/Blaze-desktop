// TextWidth is the width of s set in Helvetica (bold) at size.
func TextWidth(s string, size float64, bold bool) float64 {
	t := &helv
	if bold {
		t = &helvBold
	}
	w := 0
	for _, r := range s {
		switch {
		case r >= 32 && r <= 126:
			w += t[r-32]
		case r == '…' || r == '—':
			w += 1000
		default:
			w += 556
		}
	}
	return float64(w) * size / 1000
}
